// Writes docs/event-commands.md from the editor's command registry.
// Usage: node tools/gen-event-docs.mjs
globalThis.window = globalThis; // editor modules expect a browser global
import fs from "node:fs";
const { COMMANDS, PALETTE, PALETTE_ORDER, initialState } = await import("../editor/events/commands.js");
const { MOVE_COMMAND_NAMES, CONTINUATION_CODES } = await import("../editor/events/format.js");

const runtimeSrc = fs.readdirSync("runtime/js").filter(f => f.endsWith(".js")).map(f => fs.readFileSync("runtime/js/" + f, "utf8")).join("\n");
const implemented = new Set([...runtimeSrc.matchAll(/^\s+command(\d+)\(/gm)].map(m => Number(m[1])));
const cleanName = n => n.replace(/…$/, "");
const json = v => "`" + JSON.stringify(v) + "`";

const out = [];
out.push("# Event commands");
out.push("");
out.push("<!-- Generated by tools/gen-event-docs.mjs. Do not edit by hand. -->");
out.push("");
out.push("Event command lists are arrays of `{code, indent, parameters}`. The codes and");
out.push("parameter layouts are the same as RPG Maker MZ, so MZ references apply.");
out.push("At runtime `Game_Interpreter.prototype.commandNNN(params)` runs code NNN.");
out.push("Return `false` from a command to wait and retry it next frame.");
out.push("");
out.push("A list always ends with code `0` (an empty line at the block's indent).");
out.push("");
const seen = new Set();
for (const tab of Object.keys(PALETTE)) {
    out.push("## Palette tab " + tab);
    out.push("");
    for (const group of PALETTE[tab]) {
        out.push("### " + group);
        out.push("");
        out.push("| Code | Command | Default parameters | Runtime |");
        out.push("|---:|---|---|:---:|");
        for (const code of PALETTE_ORDER[group] || []) {
            const d = COMMANDS.get(code);
            if (!d) continue;
            seen.add(code);
            let params = [];
            try {
                params = initialState(code).params;
            } catch (e) {
                params = [];
            }
            out.push(`| ${code} | ${cleanName(d.name)} | ${json(params)} | ${implemented.has(code) ? "yes" : "**no**"} |`);
        }
        out.push("");
    }
}
const others = [...COMMANDS.values()].filter(d => !seen.has(d.code)).sort((a, b) => a.code - b.code);
if (others.length) {
    out.push("## Other commands");
    out.push("");
    out.push("Not on the palette (inserted by other commands or kept for MZ compatibility).");
    out.push("");
    out.push("| Code | Command | Runtime |");
    out.push("|---:|---|:---:|");
    for (const d of others) out.push(`| ${d.code} | ${cleanName(d.name)} | ${implemented.has(d.code) || CONTINUATION_CODES.has(d.code) ? "yes" : "**no**"} |`);
    out.push("");
}
out.push("## Continuation and block codes");
out.push("");
out.push("These lines belong to the command above them and are edited with it:");
out.push("");
out.push([...CONTINUATION_CODES].sort((a, b) => a - b).map(c => "`" + c + "`").join(", "));
out.push("");
out.push("Block ends: `411` Else, `412` End (If), `413` Repeat Above (Loop), `402`/`403`/`404`");
out.push("choice branches, `601`–`604` battle result branches.");
out.push("");
out.push("## Move route commands");
out.push("");
out.push("Used in Set Movement Route (205) and in custom autonomous movement.");
out.push("A route is `{list: [{code, parameters}], repeat, skippable, wait}`.");
out.push("");
out.push("| Code | Command |");
out.push("|---:|---|");
for (const [code, name] of Object.entries(MOVE_COMMAND_NAMES)) out.push(`| ${code} | ${name} |`);
out.push("");
fs.mkdirSync("docs", { recursive: true });
fs.writeFileSync("docs/event-commands.md", out.join("\n"));
const missing = [...COMMANDS.keys()].filter(c => !implemented.has(c) && !CONTINUATION_CODES.has(c));
console.log("Wrote docs/event-commands.md (" + COMMANDS.size + " commands). Not in runtime: " + (missing.join(", ") || "none"));
